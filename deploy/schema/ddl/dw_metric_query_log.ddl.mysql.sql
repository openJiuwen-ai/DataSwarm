CREATE TABLE IF NOT EXISTS `dw_metric_query_log` (
  `query_id`           VARCHAR(100) NOT NULL,
  `workspace_id`       VARCHAR(100) NOT NULL,
  `session_id`         VARCHAR(100) NULL,
  `question`           TEXT NULL,
  `query_spec_json`    TEXT NULL,
  `path`               VARCHAR(20) NULL,
  `authoritative`      TINYINT NULL DEFAULT 1,
  `release_id`         VARCHAR(100) NULL,
  `revision_ids_json`  TEXT NULL,
  `generated_sql`      MEDIUMTEXT NULL,
  `sql_params_json`    TEXT NULL,
  `dialect`            VARCHAR(20) NULL,
  `validation_json`    TEXT NULL,
  `executed`           TINYINT NULL DEFAULT 0,
  `row_count`          INT NULL,
  `elapsed_ms`         INT NULL,
  `model_name`         VARCHAR(100) NULL,
  `context_digest`     VARCHAR(64) NULL,
  `schema_snapshot_id` VARCHAR(100) NULL,
  `degraded_reason`    VARCHAR(500) NULL,
  `feedback`           VARCHAR(20) NULL DEFAULT 'none',
  `error_code`         VARCHAR(60) NULL,
  `error_message`      VARCHAR(1000) NULL,
  `created_at`         VARCHAR(30) NOT NULL,
  PRIMARY KEY (`query_id`),
  KEY `idx_metric_qlog_ws` (`workspace_id`, `created_at`),
  KEY `idx_metric_qlog_session` (`session_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
