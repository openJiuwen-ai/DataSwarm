  `finding_uid`         VARCHAR(400) NOT NULL,
  `source_finding_id`   VARCHAR(100) NULL,
  `finding_fingerprint` VARCHAR(64)  NULL,
  `dimension`           VARCHAR(40)  NULL,
  `severity`            VARCHAR(20)  NULL,
  `category`            VARCHAR(60)  NULL,
  `layer`               VARCHAR(20)  NULL,
  `table`               VARCHAR(200) NULL,
  `column`              VARCHAR(200) NULL,
  `task_id`             VARCHAR(100) NULL,
  `summary`             VARCHAR(1000) NULL,
  `fix_hint_strategy`   VARCHAR(60)  NULL,
