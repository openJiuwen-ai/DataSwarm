CREATE TABLE IF NOT EXISTS `dw_metric_revisions` (
  `revision_id`             VARCHAR(100) NOT NULL,
  `metric_id`               VARCHAR(100) NOT NULL,
  `workspace_id`            VARCHAR(100) NOT NULL,
  `revision_no`             INT NOT NULL,
  `metric_type`             VARCHAR(20) NULL DEFAULT 'atomic',
  `datatype`                VARCHAR(30) NULL,
  `unit`                    VARCHAR(50) NULL,
  `display_name`            VARCHAR(200) NULL,
  `synonyms`                VARCHAR(1000) NULL,
  `expression_json`         TEXT NOT NULL,
  `fixed_filters_json`      TEXT NULL,
  `time_dimension`          VARCHAR(200) NULL,
  `allowed_dimensions_json` TEXT NULL,
  `time_grains_json`        VARCHAR(200) NULL,
  `timezone`                VARCHAR(60) NULL,
  `calendar`                VARCHAR(60) NULL,
  `dependencies_json`       TEXT NULL,
  `zero_denominator`        VARCHAR(20) NULL,
  `additivity_json`         VARCHAR(200) NULL,
  `subject_iri`             VARCHAR(500) NULL,
  `status`                  VARCHAR(20) NULL DEFAULT 'draft',
  `source_type`             VARCHAR(20) NULL DEFAULT 'manual',
  `ossie_raw`               MEDIUMTEXT NULL,
  `definition_ref`          VARCHAR(300) NULL,
  `definition_hash`         VARCHAR(64) NULL,
  `created_at`              VARCHAR(30) NOT NULL,
  PRIMARY KEY (`revision_id`),
  KEY `idx_metric_rev_metric` (`metric_id`, `revision_no`),
  KEY `idx_metric_rev_ws_status` (`workspace_id`, `status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
