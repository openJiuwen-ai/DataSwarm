CREATE TABLE IF NOT EXISTS `dw_tasks` (
  `task_id`          VARCHAR(100) NOT NULL,
  `name`             VARCHAR(200) NULL,
  `description`      VARCHAR(2000) NULL,
  `executor_type`    VARCHAR(20)  NULL,
  `code`             TEXT       NULL,
  `params_json`      VARCHAR(2000) NULL,
  `datasource_ref`   VARCHAR(500) NULL,
  `timeout_s`        INT          NULL,
  `sla_minutes`      INT          NULL,
  `retry_count`      INT          NULL,
  `retry_interval_s` INT          NULL,
  `status`           VARCHAR(20)  NULL,
  `schedule_type`    VARCHAR(20)  NULL,
  `schedule_cron`    VARCHAR(100) NULL,
  `schedule_once_at` VARCHAR(50)  NULL,
  `layer`            VARCHAR(20)  NULL,
  `upstream_tasks`   VARCHAR(500) NULL,
  `output_table`     VARCHAR(200) NULL,
  `owner`            VARCHAR(50)  NULL,
  `created_at`       VARCHAR(30)  NULL,
  `updated_at`       VARCHAR(30)  NULL,
  PRIMARY KEY (`task_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
